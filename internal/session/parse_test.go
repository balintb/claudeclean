type L = fixture.Line

func parse(t *testing.T, lines ...L) meta {
	t.Helper()
	m, err := parseTranscript(bytes.NewReader(fixture.JSONL(t, lines...)))
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func userText(text string) L {
	return L{"type": "user", "message": L{"role": "user", "content": text}}
}

func TestTitlePrecedence(t *testing.T) {
	base := []L{userText("the first prompt")}
	cases := []struct {
		name  string
		extra []L
		want  string
		src   TitleSource
	}{
		{"prompt only", nil, "the first prompt", TitlePrompt},
		{"agent beats prompt", []L{{"type": "agent-name", "agentName": "Agent X"}}, "Agent X", TitleAgent},
		{"summary beats agent", []L{{"type": "agent-name", "agentName": "Agent X"}, {"type": "summary", "summary": "Sum"}}, "Sum", TitleSummary},
		{"ai beats summary", []L{{"type": "summary", "summary": "Sum"}, {"type": "ai-title", "aiTitle": "AI"}}, "AI", TitleAI},
		{"custom beats ai", []L{{"type": "custom-title", "customTitle": "Mine"}, {"type": "ai-title", "aiTitle": "AI"}}, "Mine", TitleCustom},
		{"latest ai title wins", []L{{"type": "ai-title", "aiTitle": "Old"}, {"type": "ai-title", "aiTitle": "New"}}, "New", TitleAI},
		{"blank ai title ignored", []L{{"type": "ai-title", "aiTitle": "Good"}, {"type": "ai-title", "aiTitle": "   "}}, "Good", TitleAI},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			m := parse(t, append(append([]L{}, base...), c.extra...)...)
			got, src := pickTitle(m)
			if got != c.want || src != c.src {
				t.Fatalf("got %q (%v), want %q (%v)", got, src, c.want, c.src)
			}
		})
	}
	if got, src := pickTitle(meta{}); got != "Untitled session" || src != TitleNone {
		t.Fatalf("empty: got %q %v", got, src)
	}
	if got, src := pickTitle(meta{firstCommand: "/model opus"}); got != "/model opus" || src != TitleCommand {
		t.Fatalf("command: got %q %v", got, src)
	}
}

func TestClassifyPrompt(t *testing.T) {
	cases := []struct {
		in   string
		want string
		kind promptKind
	}{
		{"fix the bug", "fix the bug", promptReal},
		{"  multi\n\nline\tprompt  ", "multi line prompt", promptReal},
		{"", "", promptNone},
		{"   ", "", promptNone},
		{"<task-notification> <task-id>b1</task-id>", "", promptNone},
		{"<bash-input>ls</bash-input>", "", promptNone},
		{"<bash-stdout>out</bash-stdout>", "", promptNone},
		{"<local-command-stdout>Set model</local-command-stdout>", "", promptNone},
		{"<system-reminder>x</system-reminder>", "", promptNone},
		{"[Request interrupted by user]", "", promptNone},
		{"This session is being continued from a previous conversation that ran out", "", promptNone},
		{"Caveat: The messages below were generated by the user", "", promptNone},
		{"<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>", "/model opus", promptCommand},
		{"<command-name>/clear</command-name><command-args></command-args>", "/clear", promptCommand},
		{"<command-message>broken</command-message>", "", promptNone},
		{"<3 this tool", "<3 this tool", promptReal},
		{"a < b and c > d", "a < b and c > d", promptReal},
		{"evil \x1b[2J\x1b]0;pwned\x07 title", "evil [2J]0;pwned title", promptReal},
		{"bidi \u202eevil\u202c zero\u200bwidth", "bidi evil zerowidth", promptReal},
	}
	for _, c := range cases {
		got, kind := classifyPrompt(c.in)
		if got != c.want || kind != c.kind {
			t.Errorf("classifyPrompt(%q) = %q, %v; want %q, %v", c.in, got, kind, c.want, c.kind)
		}
	}
}

func TestOneLineBoundsLength(t *testing.T) {
	got := oneLine(strings.Repeat("é", maxPromptRunes*3))
	if n := len([]rune(got)); n != maxPromptRunes {
		t.Fatalf("got %d runes, want %d", n, maxPromptRunes)
	}
	if oneLine("bad \xff\xfe utf8") != "bad utf8" {
		t.Fatalf("invalid UTF-8 not stripped: %q", oneLine("bad \xff\xfe utf8"))
	}
}

func TestPromptsAndMessages(t *testing.T) {
	m := parse(t,
		L{"type": "queue-operation", "content": "ignored"},
		userText("<command-name>/model</command-name><command-args>opus</command-args>"),
		userText("first real"),
		L{"type": "assistant", "message": L{"content": []L{{"type": "text", "text": "reply"}}}},
		L{"type": "user", "message": L{"content": []L{{"type": "tool_result", "content": "x"}}}},
		L{"type": "user", "message": L{"content": []L{{"type": "text", "text": "block prompt"}, {"type": "image"}}}},
		L{"type": "user", "isMeta": true, "message": L{"content": "meta text"}},
		L{"type": "user", "isSidechain": true, "message": L{"content": "sidechain text"}},
		L{"type": "assistant", "isSidechain": true},
		userText("[Request interrupted by user]"),
		userText("last real"),
		L{"type": "attachment"},
		L{"type": "system"},
	)
	if m.firstPrompt != "first real" {
		t.Errorf("firstPrompt = %q", m.firstPrompt)
	}
	if m.firstCommand != "/model opus" {
		t.Errorf("firstCommand = %q", m.firstCommand)
	}
	if m.lastTyped != "last real" {
		t.Errorf("lastTyped = %q", m.lastTyped)
	}
	if m.prompts != 3 {
		t.Errorf("prompts = %d, want 3", m.prompts)
	}
	if m.messages != 8 {
		t.Errorf("messages = %d, want 8", m.messages)
	}
}

