func TestTimestamps(t *testing.T) {
	m := parse(t,
		L{"type": "user", "timestamp": "2026-03-01T10:00:00.000Z", "message": L{"content": "a"}},
		L{"type": "assistant", "timestamp": "2026-03-01T09:00:00Z"},
		L{"type": "assistant", "timestamp": "2026-03-05T12:30:00.5Z"},
		L{"type": "assistant", "timestamp": "not a time"},
		L{"type": "assistant", "timestamp": "1970-01-01T00:00:00Z"},
		L{"type": "assistant", "timestamp": "9999-01-01T00:00:00Z"},
		L{"type": "ai-title", "aiTitle": "t", "timestamp": "2026-03-06T00:00:00Z"},
	)
	if want := time.Date(2026, 3, 1, 9, 0, 0, 0, time.UTC); !m.started.Equal(want) {
		t.Errorf("started = %v, want %v", m.started, want)
	}
	if want := time.Date(2026, 3, 6, 0, 0, 0, 0, time.UTC); !m.lastActive.Equal(want) {
		t.Errorf("lastActive = %v, want %v", m.lastActive, want)
	}
}

func TestCWDAndBranch(t *testing.T) {
	m := parse(t,
		L{"type": "user", "cwd": "/first", "gitBranch": "main", "version": "1.0", "message": L{"content": "a"}},
		L{"type": "assistant", "cwd": "/second", "gitBranch": "HEAD", "version": "1.1"},
		L{"type": "assistant", "cwd": "/sidechain", "isSidechain": true, "gitBranch": "side"},
		L{"type": "relocated", "relocatedCwd": "/moved"},
	)
	if strings.Join(m.cwds, ",") != "/moved,/first" {
		t.Errorf("cwds = %q", m.cwds)
	}
	if m.gitBranch != "main" {
		t.Errorf("gitBranch = %q (HEAD and sidechain must be ignored)", m.gitBranch)
	}
	if m.version != "1.1" {
		t.Errorf("version = %q", m.version)
	}
}

func TestPickCWD(t *testing.T) {
	if got, guessed := pickCWD("-a-b", []string{"/x", "/a/b"}); got != "/a/b" || guessed {
		t.Errorf("matching candidate not preferred: %q %v", got, guessed)
	}
	if got, guessed := pickCWD("-a-b", []string{"/x", "/y"}); got != "/x" || guessed {
		t.Errorf("first candidate not used: %q %v", got, guessed)
	}
	if got, guessed := pickCWD("-a-b", nil); got != "/a/b" || !guessed {
		t.Errorf("guess not used: %q %v", got, guessed)
	}
}

func TestMalformedInputIsSkippedNotFatal(t *testing.T) {
	in := strings.Join([]string{
		`not json at all`,
		`{"type":"user","message":{"content":"good prompt"}}`,
		`{"type":"user","message":{"content":`,
		`[1,2,3]`,
		`{"type":"user","isMeta":"yes","message":{"content":"type mismatch still parses"}}`,
		`{"type":"user","message":{"content":{"weird":"object"}}}`,
		`{"type":"user","message":{"content":[{"type":"text","text":5}]}}`,
		`{"type":"ai-title","aiTitle":42}`,
		`{"type":"assistant","timestamp":12345}`,
		``,
		`   `,
		"\x00\x01\x02",
		`{"type":"user","message":null}`,
		`null`,
	}, "\n")
	m, err := parseTranscript(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	if m.firstPrompt != "good prompt" {
		t.Errorf("firstPrompt = %q", m.firstPrompt)
	}
	if m.skipped < 3 {
		t.Errorf("skipped = %d, want at least 3", m.skipped)
	}
}

func TestOversizedLineSkipped(t *testing.T) {
	huge := `{"type":"user","message":{"content":"` + strings.Repeat("a", MaxLineBytes+10) + `"}}`
	in := huge + "\n" + `{"type":"user","message":{"content":"after"}}` + "\n"
	m, err := parseTranscript(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	if m.skipped != 1 || m.firstPrompt != "after" {
		t.Fatalf("skipped=%d firstPrompt=%q", m.skipped, m.firstPrompt)
	}
}

func FuzzParseTranscript(f *testing.F) {
	f.Add(`{"type":"user","message":{"content":"hi"},"timestamp":"2026-01-01T00:00:00Z"}`)
	f.Add(`{"type":"ai-title","aiTitle":"x"}` + "\n" + `{"type":"assistant"}`)
	f.Add(`{"type":"user","message":{"content":[{"type":"text","text":"<command-name>/x</command-name>"}]}}`)
	f.Add("\xff\xfe{}\n[]\nnull\n\"str\"")
	f.Fuzz(func(t *testing.T, in string) {
		m, err := parseTranscript(strings.NewReader(in))
		if err != nil {
			t.Fatalf("parse returned error for in-memory input: %v", err)
		}
		if m.prompts > m.messages {
			t.Fatalf("prompts %d > messages %d", m.prompts, m.messages)
		}
		if !m.started.IsZero() && m.lastActive.Before(m.started) {
			t.Fatalf("lastActive %v before started %v", m.lastActive, m.started)
		}
		title, _ := pickTitle(m)
		for _, r := range title + m.firstPrompt + m.lastPrompt + m.lastTyped {
			if r < 0x20 || r == 0x7f || (r >= 0x80 && r < 0xa0) {
				t.Fatalf("control character %U survived in display text", r)
			}
		}
	})
}
